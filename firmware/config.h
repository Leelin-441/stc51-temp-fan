/* ==========================================================================
 * 0. 类型别名（8051 上 unsigned char 是 8 位，unsigned int 是 16 位）
 * ========================================================================== */
typedef unsigned char  u8;
typedef unsigned int   u16;
typedef unsigned long  u32;
typedef signed   int   s16;

/* ==========================================================================
 * 1. 系统时钟
 * --------------------------------------------------------------------------
 *  普中/清翔开发板默认焊 11.0592MHz（串口波特率能整除，误差 0）。
 *  如果你的板子是 12MHz，只改这一行即可 —— 定时器重装值、串口波特率
 *  都会自动跟着重算。
 * ========================================================================== */
#define FOSC_HZ         11059200UL

/* ==========================================================================
 * 2. 引脚分配（**普中 PZ-51 实验板**的固定接法）
 * --------------------------------------------------------------------------
 *  功能            引脚                说明
 *  ------------------------------------------------------------------------
 *  LCD1602 D0~D7   P0.0 ~ P0.7         8 位数据模式，整口写；板上已焊上拉排阻
 *  LCD1602 RS      P2.6                0=命令 1=数据
 *  LCD1602 RW      P2.5                代码固定拉低（只写不读）
 *  LCD1602 EN      P2.7                使能，下降沿锁存
 *  LCD1602 V0      —                   接板上对比度电位器 RJ1 中间脚
 *  LED 绿          P2.0                低电平点亮
 *  LED 红          P2.1                低电平点亮
 *  蜂鸣器          P1.5                低电平响（板上三极管驱动）
 *  电机 PWM        P1.0                接 ULN2003 的 IN1
 *  DS18B20 DQ      P3.7                需 4.7k 上拉到 +5V
 *  按键 K3 (SET)   P3.2                低电平有效
 *  按键 K4 (UP)    P3.3                低电平有效
 *  串口 RXD/TXD    P3.0 / P3.1         硬件固定，9600 8N1
 *  （未使用）      P1.1~P1.4/P1.6/P1.7  空出来的 P1 口引脚，可留给扩展
 *  （未使用）      P2.2~P2.4            板载数码管的 74HC138 位选
 *
 *  ★ 为什么不把按键放在 K1(P3.1)/K2(P3.0)？
 *    那两个脚就是串口 RXD/TXD。本项目要用串口做自动化测试，
 *    所以只占用 K3/K4，把 P3.0/P3.1 完整留给串口，两者可以同时用。
 *
 *  ★ 为什么 LCD 用 P0 + P2.5~P2.7 这一组？
 *    **不是我们挑的，是板子定的。** 普中 PZ-51 上有 LCD1602 专用插座，
 *    插座内部已经出厂焊死：D0~D7 接 P0、RS/RW/E 接 P2.6/P2.5/P2.7。
 *    早期版本按"自己接线"的思路设计成 P1.1~P1.4 + P1.6 + P1.7，
 *    插到插座上完全对不上 —— 现象是**屏幕上只有一排黑方块**。
 *    教训：用开发板时，先确认板子的外设是怎么连的，再决定代码怎么写。
 *
 *  ★ P0 的代价
 *    P0 同时接到板载数码管的段选（经 74HC245），所以写 LCD 时数码管会
 *    跟着乱显示。拔掉数码管模块的电源跳线帽即可，不影响 LCD。
 * ========================================================================== */

/* ---- LCD1602 字符液晶 ----
   ★ 普中 PZ-51 实验板的 LCD1602 是插在板子的**专用插座**上的，
     插座是出厂焊死的固定接线，不能自己挑引脚：
         D0 ~ D7  ->  P0.0 ~ P0.7   （8 位模式；板上已为 P0 焊了上拉排阻）
         RS       ->  P2.6
         RW       ->  P2.5
         E        ->  P2.7
     所以驱动必须跟着板子走。早期版本按"自己接线"设计成
     P1.1~P1.4 + P1.6 + P1.7，插在插座上完全对不上，现象就是
     **屏幕只显示一排黑方块**（液晶停在上电默认状态）。
   ★ P0 是**整口写**的（`P0 = dat;`），因为 LCD 独占它；
     而 P2.5/P2.6/P2.7 用 sbit 逐位写，不会碰到 P2.0/P2.1 的 LED、
     也不会碰到 P2.2~P2.4 的数码管位选。 */
#define LCD_DATA_PORT   P0          /* 8 位数据口，整口写 */
sbit LCD_RS = P2 ^ 6;               /* 寄存器选择：0=命令 1=数据 */
sbit LCD_RW = P2 ^ 5;               /* 读写选择：固定写 0（只写不读） */
sbit LCD_EN = P2 ^ 7;               /* 使能：下降沿锁存 */
#define LCD_LINE_LEN    16          /* 每行 16 个字符，共 2 行 */

/* ---- 板载数码管：本项目改用液晶显示，只做最低限度的处理 ----
   P0 全 8 位焊在数码管段选上（经 74HC245），**而 P0 现在被 LCD 拿去当数据口了**，
   所以没法再"把 P0 拉高让数码管全灭"。
   能做的只有：把 74HC138 的位选（P2.2~P2.4）固定住，让数码管别乱扫。
   想彻底清静就拔掉数码管模块的电源跳线帽。 */
#define SMG_OFF_MASK    0x1C        /* P2.2 / P2.3 / P2.4 */

/* ---- LED ---- */
sbit LED_G = P2 ^ 0;
sbit LED_R = P2 ^ 1;
#define LED_ON          0       /* 低电平点亮 */
#define LED_OFF         1

/* ---- 蜂鸣器 ---- */
sbit BEEP = P1 ^ 5;
#define BEEP_ON         0       /* 低电平响 */
#define BEEP_OFF        1

/* ---- 电机（经 ULN2003 低边驱动）----
   ULN2003 是反相驱动器：IN 为高 → OUT 拉低（导通）→ 电机通电。
   所以软件上 MOTOR = 1 表示"通电"，是正逻辑，方便理解。 */
sbit MOTOR = P1 ^ 0;
#define MOTOR_ON        1
#define MOTOR_OFF       0

/* ---- DS18B20 单总线 ---- */
sbit DQ = P3 ^ 7;

/* ---- 按键（低电平有效）---- */
sbit KEY_SET = P3 ^ 2;          /* K3：切换 自动/手动；长按恢复默认 */
sbit KEY_UP  = P3 ^ 3;          /* K4：调目标温度 / 手动切档 */
#define KEY_PRESSED     0

/* ==========================================================================
 * 3. 控制参数
 * --------------------------------------------------------------------------
 *  ★ 温度一律用"定点数"表示：单位 0.1℃，即 350 表示 35.0℃。
 *    8051 上算浮点又慢又占 Flash（一个 float 运算能吃掉几百字节），
 *    定点整数完全够用，而且显示时直接拆位就行。
 * ========================================================================== */

/* ---- 目标温度 Tset ---- */
#define TSET_DEF        350     /* 默认目标温度 35.0℃ */
#define TSET_MIN        200     /* 可调下限 20.0℃ */
#define TSET_MAX        600     /* 可调上限 60.0℃ */
#define TSET_STEP       10      /* 每次按键调整 1.0℃ */

/* ---- 四档调速的阶梯回差（迟滞）----
   升档与降档用不同的阈值，中间留出 2℃ 的死区，避免温度在临界点
   反复抖动导致电机转速忽快忽慢。 */
#define LV_ENTER_LOW    (-20)   /* T ≥ Tset-2.0℃  进低速 */
#define LV_EXIT_LOW     (-40)   /* T ≤ Tset-4.0℃  回停机 */
#define LV_ENTER_MID    (  0)   /* T ≥ Tset       进中速 */
#define LV_EXIT_MID     (-20)   /* T ≤ Tset-2.0℃  回低速 */
#define LV_ENTER_HIGH   ( 30)   /* T ≥ Tset+3.0℃  进全速 */
#define LV_EXIT_HIGH    ( 10)   /* T ≤ Tset+1.0℃  回中速 */

/* ---- 报警 ---- */
#define ALARM_OFFSET    80      /* T ≥ Tset+8.0℃ → 报警 */
#define ALARM_EXIT      40      /* T ≤ Tset+4.0℃ 且保持够久 → 解除 */
#define ALARM_HOLD_MS   5000    /* 报警最短保持 5 秒 */

/* ---- 传感器故障保护 ---- */
#define DS_FAIL_LIMIT   3       /* 连续读失败 3 次 → 判传感器故障 */
#define DS_SAMPLE_MS    1000    /* 采样周期 1s */
#define DS_CONV_MS      800     /* 12 位转换需要 750ms，留余量 */

/* ---- PWM ----
   定时器 0 每 200us 中断一次，50 级 → PWM 周期 10ms → 频率 100Hz。
   100Hz 对 5V 小电机足够（转速平滑，且听不到明显啸叫）。 */
#define PWM_LEVELS      50
#define PWM_ISR_US      200

/* 四档占空比（百分数 0~100）。
   motor_set_duty() 会按 percent×PWM_LEVELS/100 换算成 PWM 级数：
   34% → 17 级，66% → 33 级，100% → 50 级。
   ★ 低速档不要设得太低：占空比低于约 30% 时电机转矩不足，
     会只发出"嗡嗡"声而不转，这是小电机的固有特性。 */
#define MOTOR_DUTY_STOP     0
#define MOTOR_DUTY_LOW      34
#define MOTOR_DUTY_MID      66
#define MOTOR_DUTY_HIGH     100

/* ---- 时间片 ---- */
#define TICK_MS         100     /* 状态机判定周期 */
#define OLED_MS         200     /* 显示刷新周期 */
#define LOG_MS          1000    /* 串口上报周期 */
#define KEY_SCAN_MS     20      /* 按键扫描周期（在定时器中断里） */
#define KEY_DEBOUNCE_MS 40      /* 消抖时间（2 次扫描） */
#define KEY_LONG_MS     1500    /* 长按判定 */

/* ---- 蜂鸣器节奏 ---- */
#define BEEP_TICK_MS    60      /* 状态跳变短鸣 60ms */
#define ALARM_ON_MS     150
#define ALARM_OFF_MS    150

/* ==========================================================================
 * 4. 档位 / 状态 / 模式
 * ========================================================================== */
#define LV_STOP         0
#define LV_LOW          1
#define LV_MID          2
#define LV_HIGH         3

#define MODE_AUTO       0
#define MODE_MANUAL     1

/* 对外呈现的状态名（串口上报用），顺序与 state_name() 一致 */
#define ST_INIT         0
#define ST_STOP         1
#define ST_LOW          2
#define ST_MID          3
#define ST_HIGH         4
#define ST_ALARM        5
#define ST_FAULT        6
#define ST_MANUAL       7

/* ==========================================================================
 * 5. 串口通信协议（9600 8N1）
 * --------------------------------------------------------------------------
 *  上位机 → 板卡（ASCII 文本，每条以换行结尾）：
 *      SIM T=42.5      注入模拟温度，进入仿真模式；支持小数，也支持负数
 *      SIM OFF         退出仿真，回到真实传感器
 *      MODE AUTO       切到自动模式
 *      MODE MANUAL     切到手动模式
 *      SET T=30.0      设置目标温度（限幅到 20.0 ~ 60.0℃）
 *      LEVEL 2         手动模式下直接指定档位 0~3
 *      STATUS          立即回一帧
 *      RESET           恢复默认参数并清除报警
 *
 *  板卡 → 上位机（10 个数据字段，每 1s 一帧，状态变化时立即补发）：
 *      $S,<ms>,<T>,<SET>,<LEVEL>,<DUTY>,<ST>,<MODE>,<BUZ>,<SIM>,<SENSOR>
 *      字段说明：
 *        ms     = 上电以来的毫秒数
 *        T      = 当前温度（定点 ×10，350 即 35.0℃；仿真模式下为注入值）
 *        SET    = 目标温度（×10）
 *        LEVEL  = 档位 0~3
 *        DUTY   = PWM 占空比百分数 0~100
 *        ST     = 状态名 STOP/LOW/MID/HIGH/ALARM/FAULT/MANUAL
 *        MODE   = AUTO / MANUAL
 *        BUZ    = 蜂鸣器瞬时状态 0/1
 *        SIM    = 是否处于仿真模式 0/1
 *        SENSOR = DS18B20 最近一次读取结果 OK / NOPRESENT / BADCRC / NOINIT
 *      示例：$S,12345,355,350,2,66,MID,AUTO,0,0,OK
 * ========================================================================== */
#define UART_RX_SIZE    32      /* 接收环形缓冲（放 xdata） */
#define UART_TX_SIZE    64      /* 发送缓冲（放 xdata），一帧最长约 52 字符 */
#define LINE_MAX        40      /* 单条命令行最大长度 */
#define BAUD_RATE       9600    /* ★ 9600 而不是 115200：11.0592MHz 下误差为 0 */

/* ==========================================================================
 * 6. 自检模式开关
 * --------------------------------------------------------------------------
 *  ★ 这个宏是用 #ifndef 包起来的，目的是让命令行可以覆盖它：
 *        C51.EXE app.c ... DEFINE(SELFTEST_MODE=1)
 *    于是"自检固件"可以由 tools\build_selftest.bat 单独编出一个 hex，
 *    你**不需要**手改这个宏、也就不会出现"忘了改回 0 就交作业"的情况。
 *
 *  ★ 为什么要单独出一份固件，而不是把自检代码塞进正式固件？
 *    因为自检版**不链接 app.c**（主循环根本不跑应用层），
 *    这样能省下 2KB 多 Flash。实测：
 *        正式固件（含 app.c）           code = 6362
 *        自检固件（不含 app.c）         code = 3862
 *    如果两者混在一起编，自检版会达到 8628 字节，
 *    直接超过 STC89C52 的 8192 字节 Flash 上限，根本烧不进去。
 * ========================================================================== */
#ifndef SELFTEST_MODE
#define SELFTEST_MODE   0
#endif

#endif /* __CONFIG_H__ */
