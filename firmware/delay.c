/******************************************************************************
 * @file    delay.c
 * @brief   延时实现。
 *
 *  ★ 8051 的机器周期 = 12 / 晶振频率：
 *      11.0592MHz → 1.085us
 *      12MHz      → 1.000us
 *    Keil C51 的一条 _nop_() 恰好是 1 个机器周期，所以可以用它做"精确"短延时。
 *    长延时用循环，误差大一些但 1-Wire 对长延时的上限很宽松。
 ******************************************************************************/

#include "delay.h"
#include <intrins.h>

/* 约 10us × n。
   内层 8 个 _nop_ + 循环开销 ≈ 9~10 个机器周期 ≈ 10us @11.0592MHz。
   只用于"拉低 ≥480us"这类只有下限、没有上限的场合。 */
void delay_10us(u8 n)
{
    u8 i;
    while (n--) {
        for (i = 0; i < 8; i++) {
            _nop_();
        }
    }
}

/* 约 1ms × ms。
   u16 循环变量在 8051 上是 16 位运算，每次迭代约 9~11 个机器周期，
   内层 110 次 ≈ 1100 个机器周期 ≈ 1190us @11.0592MHz。
   偏大一点是安全的（DS18B20 转换要求 ≥750ms）。 */
void delay_ms(u16 ms)
{
    u16 i;
    while (ms--) {
        for (i = 0; i < 110; i++) {
            _nop_();
        }
    }
}
