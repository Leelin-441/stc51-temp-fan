/******************************************************************************
 * @file    delay.h
 * @brief   延时函数（8051 上没有系统节拍，只能靠循环和 _nop_）。
 ******************************************************************************/

#ifndef __DELAY_H__
#define __DELAY_H__

#include "config.h"

/**
 * @brief 毫秒级延时（误差约 ±5%，本工程只用于等 DS18B20 转换，不需要精确）。
 * @note  这是**阻塞**延时。本工程只在初始化阶段和自检程序里用它；
 *        主循环里绝不能调它，否则按键会失灵（见 ds18b20.c 的非阻塞采样设计）。
 */
void delay_ms(u16 ms);

/** @brief 约 n×10us 的延时（粗延时，用于 1-Wire 的复位低电平）。 */
void delay_10us(u8 n);

#endif /* __DELAY_H__ */
