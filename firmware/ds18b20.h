/******************************************************************************
 * @file    ds18b20.h
 * @brief   DS18B20 单总线温度传感器驱动（非阻塞采样）。
 *
 *  ★ 为什么要"非阻塞"？
 *    DS18B20 做一次 12 位转换要 750ms。如果用 delay_ms(800) 死等，
 *    这 800ms 里主循环什么都干不了：按键迟钝、串口命令要排队。
 *    所以这里拆成两个阶段：
 *        阶段一 ds_task() 发起转换，同时记下时间，立刻返回
 *        阶段二 800ms 后 ds_task() 再来读结果
 *    主循环在这 800ms 里照常跑状态机、刷显示、收串口。
 *
 *  ★ 温度用定点数表示，单位 0.1℃：350 就是 35.0℃，-55 就是 -5.5℃。
 *    8051 上浮点运算又慢又占 Flash，定点整数完全够用。
 ******************************************************************************/

#ifndef __DS18B20_H__
#define __DS18B20_H__

#include "config.h"

/* 传感器状态码（会作为串口帧最后一个字段上报） */
#define DS_OK           0
#define DS_NOPRESENT    1       /* 总线上没有器件应答：没接 / 上拉缺失 / 线太长 */
#define DS_BADCRC       2       /* CRC 校验失败：读数被干扰 */
#define DS_NOINIT       3       /* 还没有成功读过一次 */

void ds_init(void);

/**
 * @brief 周期任务，主循环里不停调用。内部管理"发起转换 → 等 800ms → 读结果"。
 */
void ds_task(void);

/** @brief 最近一次成功读到的温度（×10，单位 0.1℃）。 */
s16  ds_get_temp(void);

/** @brief 最近一次的读取状态码。 */
u8   ds_get_status(void);

/** @brief 连续读取失败的次数（用于判传感器故障）。 */
u8   ds_get_fail_count(void);

/** @brief 立即强制发起一次采样（复位后用）。 */
void ds_force_sample(void);

#endif /* __DS18B20_H__ */
