#ifndef __TIMER_H__
#define __TIMER_H__

#include "config.h"

/**
 * 定时器 0 重装值。
 *
 * 工作方式 2（8 位自动重装），中断周期 T = (256 - TH0) × 12 / FOSC。
 * 要求 T = PWM_ISR_US = 200us，所以：
 *     (256 - TH0) = FOSC × 200us / 12 = FOSC / 60000
 *   11.0592MHz → 184 → 重装值 72   （实际 199.6us）
 *   12MHz      → 200 → 重装值 56   （实际 200.0us）
 * 换晶振时不用手算，改 config.h 的 FOSC_HZ 即可自动跟着变。
 */
#define TIMER0_RELOAD   ((u8)(256UL - (FOSC_HZ / 60000UL)))

void timer0_init(void);

/** @brief 上电以来的毫秒数（32 位）。 */
u32  get_ms(void);

/** @brief 毫秒数的低 16 位，用于做"差值与比较"，天然处理回绕。 */
u16  get_ms16(void);

#endif /* __TIMER_H__ */
